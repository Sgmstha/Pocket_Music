"""Generate native constants from the checked design tokens (no external dependencies)."""
import json
from pathlib import Path

root = Path(__file__).resolve().parents[2]
tokens = json.loads((root / "replica/design/tokens.json").read_text(encoding="utf-8"))
rows = ["package com.pocketmusic.android;", "", "// Generated by replica/design/generate_tokens.py; edit tokens.json instead.", "final class DesignTokens {"]
for name, value in tokens["color"].items():
    rows.append(f" static final int COLOR_{name.upper().replace('-', '_')}=0xff{value[1:]};")
for value in tokens["space"]:
    rows.append(f" static final int SPACE_{value}={value};")
for name, value in tokens["type"].items():
    rows.append(f" static final int TYPE_{name.upper()}={value['size']};")
for group in ("radius", "size"):
    for name, value in tokens[group].items():
        rows.append(f" static final int {group.upper()}_{name.upper()}={value};")
rows.append("}")
target = root / "app/src/main/java/com/pocketmusic/android/DesignTokens.java"
target.write_text("\n".join(rows) + "\n", encoding="utf-8")
print("Generated DesignTokens.java")
